export function isEquipmentLanguage(value: unknown): value is EquipmentLanguage {
  return value === 'en' || value === 'zh';
}

export function equipmentValidationMessage(language: EquipmentLanguage, message?: string) {
  if (language === 'en' || !message) return message;
  const messages: Record<string, string> = {
    'Vessel Name / IMO No. is required': '船名 / IMO 编号为必填项',
    'Lead Engineer name is required': '主管工程师姓名为必填项',
    'Select at least one copy type': '请至少选择一种副本',
  };
  return messages[message] ?? message;
}

export function equipmentChangeSummaryForLanguage(language: EquipmentLanguage, changes: EquipmentChange[]) {
  if (language === 'en') {
    if (changes.length === 0) return 'No equipment assignment changes.';
    return changes.map((change) => {
      const parts = [];
      if (change.added.length > 0) parts.push(`+${change.added.length} (${change.added.join(', ')})`);
      if (change.removed.length > 0) parts.push(`-${change.removed.length} (${change.removed.join(', ')})`);
      return `${change.itemName}: ${parts.join(' / ')}`;
    }).join('\n');
  }
  if (changes.length === 0) return '未检测到设备分配变更。';
  return changes.map((change) => {
    const parts = [];
    if (change.added.length > 0) parts.push(`新增 ${change.added.length} 个（${change.added.join(', ')}）`);
    if (change.removed.length > 0) parts.push(`移除 ${change.removed.length} 个（${change.removed.join(', ')}）`);
    return `${change.itemName}：${parts.join(' / ')}`;
  }).join('\n');
}

